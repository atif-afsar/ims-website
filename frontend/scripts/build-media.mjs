/*
 * Image & video pipeline:  npm run media
 *
 * Reads scripts/media.config.js and produces
 *   public/media/<group>/<slug>-<width>.webp   responsive images
 *   public/media/video/campus-hero.mp4         compressed 1080p hero video
 *   src/content/media.js                       manifest used by components
 *
 * Outputs that already exist are skipped; pass --force to rebuild everything.
 * Needs ffmpeg on PATH only for the drone video steps.
 */
import { existsSync, mkdirSync, writeFileSync, statSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";
import sharp from "sharp";
import entries from "./media.config.js";

const here = dirname(fileURLToPath(import.meta.url));
const frontend = resolve(here, "..");
const repo = resolve(frontend, "..");
const force = process.argv.includes("--force");

const DEFAULT_WIDTHS = [480, 960, 1600];
const QUALITY = 72;
const DRONE_VIDEO = join(repo, "Images/source-video/campus-drone-4k.mp4");
const FRAMES_DIR = join(here, ".frames");

const grades = {
  // Lift the hazy sky and warm the sandstone buildings a little
  drone: (img) => img.modulate({ brightness: 1.04, saturation: 1.18 }).linear(1.08, -10),
};

const fresh = (out, src) => !force && existsSync(out) && statSync(out).mtimeMs >= statSync(src).mtimeMs;

function ffmpeg(args) {
  execFileSync("ffmpeg", ["-v", "error", "-y", ...args], { stdio: "inherit" });
}

function prepareVideo() {
  if (!existsSync(DRONE_VIDEO)) return console.warn("! drone video not found, skipping video steps");
  mkdirSync(FRAMES_DIR, { recursive: true });
  for (const t of [5, 13, 17]) {
    const out = join(FRAMES_DIR, `aerial-${String(t).padStart(2, "0")}.png`);
    if (!fresh(out, DRONE_VIDEO)) ffmpeg(["-ss", String(t), "-i", DRONE_VIDEO, "-frames:v", "1", out]);
  }
  const videoDir = join(frontend, "public/media/video");
  mkdirSync(videoDir, { recursive: true });
  const hero = join(videoDir, "campus-hero.mp4");
  if (!fresh(hero, DRONE_VIDEO)) {
    console.log("  video  campus-hero.mp4 (1600px, muted)");
    ffmpeg(["-i", DRONE_VIDEO, "-an", "-vf", "scale=1600:-2,eq=saturation=1.15:brightness=0.02", "-c:v", "libx264", "-preset", "slow", "-crf", "31", "-pix_fmt", "yuv420p", "-movflags", "+faststart", hero]);
  }
}

async function buildImage(entry) {
  const src = join(repo, entry.src);
  if (!existsSync(src)) throw new Error(`missing source for ${entry.slug}: ${entry.src}`);

  const base = () => {
    let img = sharp(src).rotate(); // respect camera orientation
    if (entry.crop) {
      const [left, top, width, height] = entry.crop;
      img = img.extract({ left, top, width, height });
    }
    return entry.grade ? grades[entry.grade](img) : img;
  };

  const { width: srcW, height: srcH } = await base().toBuffer({ resolveWithObject: true }).then((r) => r.info);
  const widths = (entry.widths || DEFAULT_WIDTHS).filter((w, i, all) => w < srcW || i === 0).map((w) => Math.min(w, srcW));
  const outDir = join(frontend, "public/media", entry.group);
  mkdirSync(outDir, { recursive: true });

  const files = [];
  for (const w of [...new Set(widths)]) {
    const name = `${entry.slug}-${w}.webp`;
    const out = join(outDir, name);
    if (!fresh(out, src)) await base().resize({ width: w }).webp({ quality: QUALITY, effort: 5 }).toFile(out);
    files.push({ w, url: `/media/${entry.group}/${name}` });
  }

  // Tiny blurred preview shown while the real image loads
  const lqip = await base().resize({ width: 24 }).blur(1).webp({ quality: 40 }).toBuffer();

  const largest = files[files.length - 1];
  return {
    src: largest.url,
    srcSet: files.map((f) => `${f.url} ${f.w}w`).join(", "),
    width: srcW,
    height: srcH,
    alt: entry.alt,
    group: entry.group,
    placeholder: `data:image/webp;base64,${lqip.toString("base64")}`,
  };
}

prepareVideo();

const slugs = new Set();
const manifest = {};
for (const entry of entries) {
  if (slugs.has(entry.slug)) throw new Error(`duplicate slug ${entry.slug}`);
  slugs.add(entry.slug);
  manifest[entry.slug] = await buildImage(entry);
  process.stdout.write(`  image  ${entry.slug}\n`);
}

const banner = "// Generated by scripts/build-media.mjs - do not edit by hand. Run `npm run media`.\n";
const outFile = join(frontend, "src/content/media.js");
mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, `${banner}const media = ${JSON.stringify(manifest, null, 2)};\n\nexport default media;\n`);
console.log(`\n${Object.keys(manifest).length} images → src/content/media.js`);
