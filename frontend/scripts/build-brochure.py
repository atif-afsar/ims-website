"""
Brochure pipeline:  npm run brochure

Reads the original brochure PDF (git-ignored, in Images/source-pdf/) and writes
  public/media/brochure/page-NN-<w>.webp   page images for the on-site viewer
  public/pdfs/ims-brochure.pdf             compressed PDF for download
  src/content/brochure.js                  manifest used by the viewer

Needs PyMuPDF (pip install pymupdf). Run again whenever the brochure changes.
"""
import io
import json
import sys
from pathlib import Path

import fitz  # PyMuPDF
from PIL import Image

FRONTEND = Path(__file__).resolve().parent.parent
REPO = FRONTEND.parent
SOURCE = REPO / "Images" / "source-pdf" / "brochure.pdf"
OUT_DIR = FRONTEND / "public" / "media" / "brochure"
OUT_PDF = FRONTEND / "public" / "pdfs" / "ims-brochure.pdf"
MANIFEST = FRONTEND / "src" / "content" / "brochure.js"

WIDTHS = [240, 640, 1200]   # thumbnail + viewer sizes
PDF_DPI = 150          # print-quality for the download
WEBP_QUALITY = 78
JPEG_QUALITY = 80


def render(page, dpi):
    pix = page.get_pixmap(dpi=dpi, alpha=False)
    return Image.frombytes("RGB", (pix.width, pix.height), pix.samples)


def main():
    if not SOURCE.exists():
        sys.exit(f"Original brochure not found: {SOURCE}")
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    src = fitz.open(SOURCE)
    out = fitz.open()
    pages = []

    for i, page in enumerate(src, start=1):
        img = render(page, PDF_DPI)

        files = []
        for w in WIDTHS:
            name = f"page-{i:02d}-{w}.webp"
            h = round(img.height * w / img.width)
            img.resize((w, h), Image.LANCZOS).save(OUT_DIR / name, "WEBP", quality=WEBP_QUALITY, method=5)
            files.append((w, f"/media/brochure/{name}"))

        # Compressed PDF page at the original page size
        buf = io.BytesIO()
        img.save(buf, "JPEG", quality=JPEG_QUALITY, optimize=True, progressive=True)
        new_page = out.new_page(width=page.rect.width, height=page.rect.height)
        new_page.insert_image(new_page.rect, stream=buf.getvalue())

        pages.append({
            "src": files[-1][1],
            "srcSet": ", ".join(f"{url} {w}w" for w, url in files),
            "width": WIDTHS[-1],
            "height": round(img.height * WIDTHS[-1] / img.width),
        })
        print(f"  page {i:02d}")

    out.save(OUT_PDF, garbage=4, deflate=True)
    banner = "// Generated by scripts/build-brochure.py - do not edit by hand. Run `npm run brochure`.\n"
    MANIFEST.write_text(
        banner + "const brochure = " + json.dumps({"pdf": "/pdfs/ims-brochure.pdf", "pages": pages}, indent=2) + ";\n\nexport default brochure;\n",
        encoding="utf-8",
    )
    print(f"\n{len(pages)} pages; PDF {OUT_PDF.stat().st_size / 1e6:.1f} MB (was {SOURCE.stat().st_size / 1e6:.1f} MB)")


if __name__ == "__main__":
    main()
